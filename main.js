function splitSyncRows(raw) {
  const rows = [];
  for (const line of (raw || "").split(/\r?\n/)) {
    const t = line.trim();
    if (!t)
      continue;
    const i = t.indexOf(":");
    if (i === -1)
      rows.push({ sanity: t, fm: "" });
    else
      rows.push({
        sanity: t.slice(0, i).trim(),
        fm: t.slice(i + 1).trim()
      });
  }
  while (rows.length < 10)
    rows.push({ sanity: "", fm: "" });
  return rows;
}
